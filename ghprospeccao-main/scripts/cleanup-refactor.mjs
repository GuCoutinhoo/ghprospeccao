import fs from 'node:fs';
const file='src/components/layout/Sidebar.tsx';
let source=fs.readFileSync(file,'utf8');
const start=source.indexOf('      {/* Modal de Senha para Acesso ao Painel Geral */}');
const end=source.lastIndexOf('    </>');
if(start<0 || end<start)throw new Error('Unexpected Sidebar layout');
source=source.slice(0,start)+source.slice(end);
source=source.replace(/  const \[(isPasswordModalOpen|passwordInput|passwordError|showPassword),[^\n]+\n/g,'');
source=source.replace(/onClick=\{\(\) => \{\s*setPasswordInput\(''\);\s*setPasswordError\(false\);\s*setShowPassword\(false\);\s*setIsPasswordModalOpen\(true\);\s*\}\}/,"onClick={async () => {await onLogout();window.location.assign('/admin');}}");
source=source.replace('Acessar o Painel Geral (requer senha)','Entrar como administrador');
fs.writeFileSync(file,source);
